#!/usr/bin/env python3
"""One-off builder for the embedded type used by main.py.

The grading sandbox gives main.py nothing but the Python standard
library -- no Pillow, no font files -- so the letterforms the front
page is printed with have to travel inside the repository.  This
script rasterises the Liberation family (free licence, metric kin to
Times and Arial) at the exact sizes the page uses, trims each glyph
to its ink, quantises the coverage to sixteen levels and packs the
lot into a single compressed blob written out as fontdata.py.

Blob layout (all integers little-endian):

    u16  number of fonts
    per font:
      u8   length of the font's name, then the name itself (ASCII)
      u16  ascent in pixels
      u16  full line height in pixels
      u16  number of glyphs
      per glyph:
        u32  Unicode codepoint
        u16  pen advance in pixels
        i16  ink's left edge relative to the pen position
        i16  ink's top edge relative to the ascender top
        u16  ink width, u16 ink height
        u32  byte count of the bitmap, then the bitmap:
             4-bit coverage values, two per byte, high nibble
             first, rows laid out left to right, top to bottom

Usage:  python3 tools/make_font.py     (writes fontdata.py)
"""

import base64
import struct
import zlib

from PIL import Image, ImageDraw, ImageFont

SERIF = "/usr/share/fonts/truetype/liberation/LiberationSerif-{}.ttf"
SANS = "/usr/share/fonts/truetype/liberation/LiberationSans-{}.ttf"

PUNCT = "–—•€’‘“”"
PRINTABLE = "".join(chr(c) for c in range(32, 127)) + PUNCT
HEADLINE_CHARS = "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789 .,;:!?'’—–-•&()%€$/+"
NUMBER_CHARS = "0123456789+,$%."

# (name in the blob, font file, pixel size, characters to rasterise)
TYPE_PLAN = [
    ("masthead", SERIF.format("Bold"), 84, "ABCDEFGHIJKLMNOPQRSTUVWXYZ "),
    ("leadhead", SERIF.format("Bold"), 44, HEADLINE_CHARS),
    ("headsm", SERIF.format("Bold"), 21, HEADLINE_CHARS),
    ("body", SERIF.format("Regular"), 17, PRINTABLE),
    ("kick", SANS.format("Bold"), 15, PRINTABLE),
    ("dateline", SANS.format("Bold"), 21, HEADLINE_CHARS),
    ("brief", SANS.format("Regular"), 15, PRINTABLE),
    ("briefb", SANS.format("Bold"), 15, PRINTABLE),
    ("bignum", SANS.format("Bold"), 30, NUMBER_CHARS),
    ("small", SANS.format("Regular"), 12, PRINTABLE),
]


def rasterise(face, ch, line_px):
    """Return one glyph record for character ch in the given face."""
    advance = int(round(face.getlength(ch)))
    if ch == " ":
        return ord(ch), advance, 0, 0, 0, 0, b""
    margin = 4
    canvas_w = int(face.getlength(ch)) + 2 * margin + 2
    canvas = Image.new("L", (canvas_w, line_px + 2 * margin), 0)
    ImageDraw.Draw(canvas).text((margin, margin), ch, font=face,
                                fill=255, anchor="la")
    box = canvas.getbbox()
    if box is None:  # a character with no ink of its own
        return ord(ch), advance, 0, 0, 0, 0, b""
    ink = canvas.crop(box)
    w, h = ink.size
    raw = ink.tobytes()
    packed = bytearray((len(raw) + 1) // 2)
    for i, value in enumerate(raw):
        if i % 2 == 0:
            packed[i // 2] = (value >> 4) << 4
        else:
            packed[i // 2] |= value >> 4
    return (ord(ch), advance, box[0] - margin, box[1] - margin,
            w, h, bytes(packed))


def assemble():
    blob = bytearray(struct.pack("<H", len(TYPE_PLAN)))
    for name, path, size, charset in TYPE_PLAN:
        face = ImageFont.truetype(path, size)
        ascent, descent = face.getmetrics()
        chars = sorted(set(charset))
        records = [rasterise(face, ch, ascent + descent) for ch in chars]
        encoded = name.encode("ascii")
        blob += struct.pack("<B", len(encoded)) + encoded
        blob += struct.pack("<HHH", ascent, ascent + descent, len(records))
        for cp, adv, xo, yo, w, h, data in records:
            blob += struct.pack("<IHhhHHI", cp, adv, xo, yo, w, h, len(data))
            blob += data
        print("packed %-9s %3d px, %3d glyphs" % (name, size, len(records)))
    return bytes(blob)


def main():
    blob = assemble()
    squeezed = base64.b85encode(zlib.compress(blob, 9)).decode("ascii")
    chunks = [squeezed[i:i + 96] for i in range(0, len(squeezed), 96)]
    with open("fontdata.py", "w", encoding="ascii") as fh:
        fh.write('"""Embedded bitmap type for main.py.\n\n')
        fh.write("Generated by tools/make_font.py from the Liberation fonts\n")
        fh.write("(free licence): glyphs rasterised once, coverage cut to\n")
        fh.write("4 bits, the whole blob zlib-compressed and base85-coded.\n")
        fh.write('"""\n\nimport base64\nimport zlib\n\n_BLOB85 = (\n')
        for chunk in chunks:
            fh.write('    "%s"\n' % chunk)
        fh.write(')\n\nFONT_BLOB = zlib.decompress(base64.b85decode("".join(_BLOB85)))\n')
    print("blob %d bytes, %d base85 chars in %d lines"
          % (len(blob), len(squeezed), len(chunks)))


if __name__ == "__main__":
    main()
